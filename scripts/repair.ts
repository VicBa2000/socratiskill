/**
 * repair.ts — CLI del subcomando repair.
 *
 * Devuelve la salida que `resume` no puede dar. Cuando hay dos profiles
 * en disco, resume.sh aborta por diseño: no puede saber cual le importa
 * al usuario, y adivinar seria pisarle la calibracion. Correcto, pero
 * deja al usuario sin camino — y el estado que lo produjo (el bug B1) no
 * fue culpa suya. Este comando cierra ese callejon.
 *
 * DOS PASOS, NO UNO. Sin `--apply` solo diagnostica e imprime que haria.
 * Borrar el profile de alguien es irreversible y este comando existe
 * justamente porque el plugin ya le rompio el estado una vez; hacerlo en
 * un solo paso seria pedirle que confie dos veces. El dispatcher de
 * SKILL.md muestra el diagnostico primero y pide confirmacion.
 *
 * NO REPARA "ambiguous". Cuando el profile activo tiene configuracion
 * real, elegir por el usuario es exactamente el error que se quiere
 * evitar: imprime los dos y le da los dos comandos.
 *
 * Uso:
 *   bun run repair.ts             # diagnostica, no toca nada
 *   bun run repair.ts --apply     # aplica la reparacion segura
 *
 * Exit codes:
 *   0  nada que reparar, o reparacion aplicada
 *   1  hay algo que reparar (solo diagnostico, todavia sin aplicar)
 *   2  argumento invalido
 *   3  requiere decision del usuario (ambiguous): no se aplica solo
 */

import { existsSync, renameSync, unlinkSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"
import { ProfileHealth } from "./profile-health"

function stateDir(): string {
  return process.env["SOCRATIC_STATE_DIR"] ?? join(homedir(), ".claude", "socratic")
}

const out = (s: string): void => void process.stdout.write(s + "\n")

function main(): void {
  const args = process.argv.slice(2)
  let apply = false
  for (const a of args) {
    if (a === "--apply") apply = true
    else {
      process.stderr.write(`unknown flag: ${a}\n`)
      process.exit(2)
    }
  }

  const dir = stateDir()
  const { active, paused } = ProfileHealth.paths(dir)
  const d = ProfileHealth.inspect(dir)

  // Siempre primero, incluso cuando no hay nada que reparar: la pregunta
  // "es el bug o estoy corriendo codigo viejo?" no se puede contestar sin
  // esto, y es la primera que aparece cuando un fix "no funciono".
  const version = ProfileHealth.runningVersion()
  out(`running: v${version ?? "?"}  (${ProfileHealth.runningFrom()})`)
  out("  this is the code executing the hooks, which is not necessarily what /plugin reports.")
  out("")

  if (d.kind === "ok") {
    out("[ok] state is consistent — nothing to repair.")
    process.exit(0)
  }

  if (d.kind === "ambiguous") {
    out("[conflict] two profiles exist and BOTH carry real settings.")
    out(`  active: ${active}${d.activeLevel !== null ? `  (level ${d.activeLevel})` : ""}`)
    out(`  paused: ${paused}${d.pausedLevel !== null ? `  (level ${d.pausedLevel})` : ""}`)
    out("")
    out("this one is yours to decide — repair will not pick for you.")
    out("  keep the active one:  rm " + paused)
    out("  keep the paused one:  rm " + active + " && /socratiskill:socratic resume")
    process.exit(3)
  }

  if (d.kind === "orphan") {
    out("[found] profile.json was auto-generated by the Stop hook, not by calibration.")
    out(`  its level (${d.activeLevel ?? "?"}) is a default nobody chose.`)
    out("  there is no paused profile to restore — the original level is gone.")
    out("")
    if (!apply) {
      out("repair would DELETE that profile so the plugin stops pretending it is calibrated.")
      out("afterwards run /socratiskill:socratic calibrate, or set your level directly.")
      out("")
      out("to apply: /socratiskill:socratic repair --apply")
      process.exit(1)
    }
    unlinkSync(active)
    out(`[repaired] deleted ${active}`)
    out("run /socratiskill:socratic calibrate to set your level.")
    process.exit(0)
  }

  // resurrected — el unico caso con una respuesta correcta obvia.
  out("[found] the known pause bug (fixed in v0.5.3) left two profiles on disk.")
  out(`  active: ${active}`)
  out(`          auto-generated by the Stop hook; level ${d.activeLevel ?? "?"} is a default, not your choice.`)
  out(`  paused: ${paused}`)
  out(`          your real profile${d.pausedLevel !== null ? `, at level ${d.pausedLevel}` : ""}.`)
  out("")
  // Impreso ANTES de cualquier mutacion, y a proposito: --apply borra el
  // artefacto, o sea que se lleva puesta la unica evidencia de cuando
  // ocurrio el daño.
  if (d.artifactWrittenAt) {
    out(`the damage was done at: ${d.artifactWrittenAt}  (running v${version ?? "?"} now)`)
    out("  if that timestamp is BEFORE you updated the plugin, this is leftover state and")
    out("  the code fix is working — the residue simply outlived it, which is what repair is for.")
    out("  if it is AFTER, the bug is still live and this is worth reporting.")
    out("")
  }

  if (!apply) {
    out("repair would discard the auto-generated one and restore yours.")
    out("to apply: /socratiskill:socratic repair --apply")
    process.exit(1)
  }

  // Orden deliberado: primero se borra el artefacto, despues se renombra.
  // Al reves, un fallo entre los dos pasos dejaria al usuario SIN ningun
  // profile; asi, el peor caso intermedio es el estado que ya tenia.
  unlinkSync(active)
  renameSync(paused, active)

  // El silencer es un one-shot de la pausa. Sobrevivirle al resume haria
  // que el primer turno reactivado le dijera al modelo que ignore el
  // plugin.
  const marker = join(dir, ".pause-silencer-pending")
  if (existsSync(marker)) {
    try {
      unlinkSync(marker)
    } catch {
      /* best-effort */
    }
  }

  out("[repaired] discarded the auto-generated profile and restored yours.")
  out(`           level ${d.pausedLevel ?? "?"} is active again on the next turn.`)
  process.exit(0)
}

main()
